let lang = document.documentElement.lang === 'en' ? 'en' : 'ar';

export const getLang = () => lang;
export const isRTL = () => lang === 'ar';

export function setLang(next) {
  lang = next === 'en' ? 'en' : 'ar';
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
}

/** Translate a key, filling {placeholders}. Placeholder values are inserted as-is. */
export function t(key, vars) {
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}

/** Pick the current language from a bilingual { ar, en } value. */
export const L = (obj) => (obj && typeof obj === 'object' ? obj[lang] ?? obj.en : obj ?? '');

// ----- Formatting (Latin digits in both languages keep figures easy to scan) -----
const locale = () => (lang === 'ar' ? 'ar-EG-u-nu-latn' : 'en-GB');

export function fmtNum(n, opts = {}) {
  return new Intl.NumberFormat(locale(), { maximumFractionDigits: 0, ...opts }).format(n);
}

export function fmtMoney(n, { compact = false } = {}) {
  const v = compact ? fmtCompact(n) : fmtNum(Math.round(n));
  return lang === 'ar' ? `${v} ج.م` : `EGP ${v}`;
}

export function fmtCompact(n) {
  return new Intl.NumberFormat(lang === 'ar' ? 'en-US' : 'en-US', { notation: 'compact', maximumFractionDigits: n >= 1e6 ? 2 : 1 }).format(n);
}

export function fmtPct(n, digits = 1) {
  return `${fmtNum(n, { maximumFractionDigits: digits, minimumFractionDigits: 0 })}%`;
}

export function fmtTime(ts) {
  return new Intl.DateTimeFormat(locale(), { hour: 'numeric', minute: '2-digit' }).format(ts);
}

export function fmtDate(ts, opts = { day: 'numeric', month: 'short' }) {
  return new Intl.DateTimeFormat(locale(), opts).format(ts);
}

export function fmtDateTime(ts) {
  return new Intl.DateTimeFormat(locale(), { day: 'numeric', month: 'short', hour: 'numeric', minute: '2-digit' }).format(ts);
}

export function fmtHour(h) {
  const d = new Date(2026, 0, 1, h);
  return new Intl.DateTimeFormat(locale(), { hour: 'numeric' }).format(d);
}

export function fmtAgo(ts, now = Date.now()) {
  const m = Math.floor((now - ts) / 60000);
  if (m < 1) return t('ago.now');
  if (m < 60) return t('ago.min', { n: m });
  const h = Math.floor(m / 60);
  if (h < 24) return t('ago.hour', { n: h });
  return t('ago.day', { n: Math.floor(h / 24) });
}
